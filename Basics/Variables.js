//Covering: Variables and their declaration in JavaScript

// Declaring a variable using var
var age = 25;
console.log("Age using var:", age); // Output: Age using var: 25
/*
Characteristics of var:
1. Function-scoped
2. Can be redeclared
3. Can be reassigned
4. Hoisted to the top of the scope
*/

// Declaring a variable using let
let name = "John";
console.log("Name using let:", name);
// Output: Name using let: John
/*
Characteristics of let:
1. Block-scoped
2. Cannot be redeclared
3. Can be reassigned
4. Hoisted to the top of the block
*/  
// Declaring a variable using const
const pi = 3.14;
console.log("Value of pi using const:", pi);
// Output: Value of pi using const: 3.14
/*
Characteristics of const:
1. Block-scoped
2. Cannot be redeclared
3. Cannot be reassigned
4. Hoisted to the top of the block
*/